const CHARS = Object.keys(G);

export function pixelFont(colors) {
  const names = Object.keys(colors);
  const atlas = document.createElement('canvas');
  atlas.width = CHARS.length * 6; atlas.height = names.length * 8;
  const a = atlas.getContext('2d');
  names.forEach((n, ci) => {
    a.fillStyle = colors[n];
    CHARS.forEach((ch, gi) => G[ch].split(',').forEach((row, ry) => { const v = parseInt(row, 2); for (let x = 0; x < 5; x++) if (v & (16 >> x)) a.fillRect(gi * 6 + x, ci * 8 + ry, 1, 1); }));
  });
  const index = new Int16Array(128).fill(-1);
  CHARS.forEach((ch, i) => { index[ch.charCodeAt(0)] = i; });
  const lower = c => (c >= 97 && c <= 122 && c !== 118 ? c - 32 : c); // 'v' is the down arrow
  const row = {}; names.forEach((n, i) => { row[n] = i * 8; });
  const width = (s, scale = 1) => s.length * 6 * scale - scale;
  function glyph(ctx, code, x, y, cy, scale) {
    const gi = index[lower(code)]; if (gi < 0) return;
    ctx.drawImage(atlas, gi * 6, cy, 5, 7, x, y, 5 * scale, 7 * scale);
  }
  function text(ctx, s, x, y, color = names[0], scale = 1, align = 'left') {
    const cy = row[color] ?? 0;
    if (align === 'center') x = Math.round(x - width(s, scale) / 2); else if (align === 'right') x -= width(s, scale);
    for (let i = 0; i < s.length; i++) glyph(ctx, s.charCodeAt(i), x + i * 6 * scale, y, cy, scale);
  }
  // integer, zero padded to `digits` (0 = no padding), right edge at x when align='right'
  function num(ctx, n, digits, x, y, color = names[0], scale = 1, align = 'left') {
    n = Math.max(0, Math.floor(n));
    let len = 1; for (let m = n; m >= 10; m = Math.floor(m / 10)) len++;
    if (digits > len) len = digits;
    if (align === 'right') x -= len * 6 * scale - scale; else if (align === 'center') x = Math.round(x - (len * 6 * scale - scale) / 2);
    const cy = row[color] ?? 0;
    for (let i = len - 1; i >= 0; i--) { glyph(ctx, 48 + (n % 10), x + i * 6 * scale, y, cy, scale); n = Math.floor(n / 10); }
  }
  return { text, num, width, atlas };
}
